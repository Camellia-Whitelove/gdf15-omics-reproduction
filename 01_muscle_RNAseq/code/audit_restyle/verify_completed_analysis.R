source('01_muscle_RNAseq/code/common.R')
.libPaths(c(normalizePath('01_muscle_RNAseq/R-library', mustWork=FALSE),.libPaths()))
suppressPackageStartupMessages(library(DESeq2))
meta<-read.csv('01_muscle_RNAseq/outputs/sample_metadata.csv')
counts<-readRDS('01_muscle_RNAseq/outputs/gene_fragment_counts.rds')
dds<-readRDS('01_muscle_RNAseq/outputs/statistics/deseq2_model.rds')
alignment<-read.csv('01_muscle_RNAseq/outputs/alignment/alignment_summary.csv')
stopifnot(ncol(counts)==16,ncol(dds)==16,nrow(meta)==16,nrow(alignment)==16)
stopifnot(identical(colnames(counts),meta$sample_alias),identical(colnames(dds),meta$sample_alias))
stopifnot(all(colSums(counts)==alignment$assigned_pairs[match(meta$sample_alias,alignment$GSM)]))
stopifnot(all(!is.na(dispersions(dds))),all(dispersions(dds)>0))
ready<-paste0('01_muscle_RNAseq/data/bam_unique/',meta$run_accession,'.bam.ready')
stopifnot(all(file.exists(ready)))
cat('Unique alignment and count integrity markers: 16/16 PASS\n')
cat('Count matrix:',nrow(counts),'genes x',ncol(counts),'samples\n')
cat('Fitted DESeq2 model:',nrow(dds),'genes x',ncol(dds),'samples\n')
for(name in c('GDF15_vs_Pairfed','GDF15_vs_Vehicle','Pairfed_vs_Vehicle')){
 tab<-read.csv(paste0('01_muscle_RNAseq/outputs/statistics/',name,'.csv'))
 stopifnot(nrow(tab)==nrow(dds),identical(tab$gene_id,rownames(dds)))
 cat(name,':',sum(tab$DEG),'DEGs; full result table PASS\n')
}
cat('GO MF: analysis executed, 0 terms pass BH padj < 0.1; Fig4c result not reproduced\n')

